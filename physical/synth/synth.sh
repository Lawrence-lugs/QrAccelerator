#!/usr/bin/env bash
# Synthesis driver for the digital QR accelerator top.
set -euo pipefail

TARGET=${1:-generic}
FRONTEND=${FRONTEND:-auto}
PDK_ROOT=${PDK_ROOT:-/foss/pdks}
PDK=${PDK:-ihp-sg13g2}
BLOCK=${BLOCK:-output_scaler}

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
PHYS="$ROOT/physical"
BUILD="$PHYS/build"
LOGS="$BUILD/logs"
mkdir -p "$BUILD/generic" "$BUILD/ihp" "$LOGS" "$PHYS/reports"

cd "$ROOT"

FILES=()
while IFS= read -r line; do
    line=${line%$'\r'}
    line=${line%%#*}
    line=${line//[[:space:]]/}
    [ -n "$line" ] && FILES+=("$line")
done < "$PHYS/synth/rtl.f"

if [ "${#FILES[@]}" -eq 0 ]; then
    echo "error: no RTL files listed in physical/synth/rtl.f" >&2
    exit 1
fi

SLANG_LOAD=()
if yosys -m slang -p "help read_slang" >/dev/null 2>&1; then
    SLANG_LOAD=(-m slang)
fi

FRONTEND_OPTS=()
READ_CMD=""

frontend_args() {
    case "$1" in
        slang)
            FRONTEND_OPTS=("${SLANG_LOAD[@]}")
            READ_CMD="read_slang --single-unit --top qr_acc_top -I rtl ${FILES[*]}"
            ;;
        verilog)
            FRONTEND_OPTS=()
            READ_CMD="read_verilog -sv -I rtl ${FILES[*]}"
            ;;
        sv2v)
            sv2v -I rtl "${FILES[@]}" -w "$BUILD/design.sv2v.v"
            FRONTEND_OPTS=()
            READ_CMD="read_verilog $BUILD/design.sv2v.v"
            ;;
        *)
            echo "error: unknown frontend '$1' (expected slang|verilog|sv2v)" >&2
            return 1
            ;;
    esac
}

liberty_file() {
    local lib
    lib=$(find "$PDK_ROOT/$PDK/libs.ref/sg13g2_stdcell/lib" -maxdepth 1 -name '*.lib' 2>/dev/null \
        | sort | grep -Ei 'typ.*(25C|1p20V)' | head -n1 || true)
    if [ -z "$lib" ]; then
        lib=$(find "$PDK_ROOT/$PDK/libs.ref" -name '*.lib' 2>/dev/null | sort | head -n1 || true)
    fi
    if [ -z "$lib" ]; then
        echo "error: no liberty file found under $PDK_ROOT/$PDK" >&2
        return 1
    fi
    printf '%s\n' "$lib"
}

# Yosys runs -p commands and -s scripts in separate phases, so the read command
# and the passes must live in one generated script to preserve order.
write_script() {
    local out=$1 body=${2:-}
    {
        echo "# generated by physical/synth/synth.sh"
        echo "$READ_CMD"
        cat "$PHYS/synth/elaborate.ys"
        if [ -n "$body" ]; then
            cat "$body"
        else
            echo "stat"
        fi
    } > "$out"
}

run_script() {
    local script=$1 log=$2
    yosys "${FRONTEND_OPTS[@]}" -s "$script" -l "$log"
}

try_frontend() {
    frontend_args "$1" || return 1
    write_script "$BUILD/elab_$1.ys" ""
    run_script "$BUILD/elab_$1.ys" "$LOGS/frontend_$1.log" >/dev/null 2>&1
}

if [ "$FRONTEND" = auto ]; then
    for fe in slang verilog sv2v; do
        if try_frontend "$fe"; then
            FRONTEND=$fe
            break
        fi
    done
    if [ "$FRONTEND" = auto ]; then
        echo "error: none of slang/verilog/sv2v elaborated qr_acc_top" >&2
        echo "see $LOGS/frontend_*.log" >&2
        exit 1
    fi
fi

echo "frontend: $FRONTEND"
frontend_args "$FRONTEND"

case "$TARGET" in
    elaborate)
        write_script "$BUILD/elaborate.ys" ""
        run_script "$BUILD/elaborate.ys" "$LOGS/elaborate.log"
        ;;
    generic)
        write_script "$BUILD/generic.ys" "$PHYS/synth/generic.ys"
        run_script "$BUILD/generic.ys" "$LOGS/generic.log"
        ;;
    block)
        LIB=$(liberty_file)
        echo "block: $BLOCK"
        echo "liberty: $LIB"
        {
            echo "# generated by physical/synth/synth.sh"
            echo "$READ_CMD"
            echo "blackbox ram_2w2r"
            echo "hierarchy -check -top $BLOCK"
            echo "proc"
            echo "delete t:\$print"
            echo "synth -run begin:fine"
            echo "techmap"
            echo "dfflibmap -liberty $LIB"
            echo "abc -fast -liberty $LIB"
            echo "opt_clean"
            echo "tee -o physical/reports/ihp_${BLOCK}_check.rpt check"
            echo "tee -o physical/reports/ihp_${BLOCK}_area.rpt stat -liberty $LIB"
            echo "write_verilog -noattr -noexpr physical/build/ihp/${BLOCK}.v"
        } > "$BUILD/block_$BLOCK.ys"
        run_script "$BUILD/block_$BLOCK.ys" "$LOGS/ihp_$BLOCK.log"
        ;;
    *)
        echo "error: unknown target '$TARGET' (expected elaborate|generic|block)" >&2
        exit 2
        ;;
esac
