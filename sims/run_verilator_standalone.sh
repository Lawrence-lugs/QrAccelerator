#!/usr/bin/env bash
# Standalone Verilator runner for QrAccelerator testbenches (no Python orchestrator).
#
# Usage:
#   bash sims/run_verilator_standalone.sh <tb_name> [--help]
#
# Testbench classes:
#   RUNS STANDALONE      : tb_column, tb_afl        (no input files)
#   CLEAN ERROR          : tb_qracc, tb_seq_acc, tb_qracc_top  (need generated inputs)
#   PROPRIETARY          : tb_q_redis               (xrun only, not verilator)
#
# Works from repo root: `cd "$(dirname "$0")/.."` then `cd sims` before running.
# Mirrors the verilator argument list from tests/utils.py sim_args['verilator']
# (the +define+QRACC_PARAMS_FILE define is intentionally omitted here: standalone
# runs use rtl/qracc_params_defaults.svh via the `else` branch of the conditional
# include in qr_acc_top.sv / qr_acc_top_wrapper.sv).
set -euo pipefail

cd "$(dirname "$0")/.."
cd sims

VERILATOR_ARGS=(
    --binary --timing -j 0 -sv
    +incdir+../rtl
    -Wno-fatal -Wno-WIDTHEXPAND -Wno-WIDTHTRUNC -Wno-UNUSEDSIGNAL -Wno-UNDRIVEN
    -Wno-UNUSEDPARAM -Wno-PINMISSING -Wno-GENUNNAMED -Wno-CASEINCOMPLETE
    -Wno-TIMESCALEMOD -Wno-IMPLICITSTATIC -Wno-LATCH -Wno-COMBDLY -Wno-BLKSEQ -Wno-INITIALDLY
    -CFLAGS -O1
)

usage() {
    cat <<EOF
Usage: $0 <tb_name>

Run a Verilator simulation of <tb> standalone (no pytest).

Testbenches:
  tb_column        RUNS STANDALONE        (prints TEST SUCCESS)
  tb_afl           RUNS STANDALONE        (prints TEST SUCCESS)
  tb_qracc         CLEAN ERROR            (needs tb/qracc/inputs/* generated by pytest)
  tb_seq_acc       CLEAN ERROR            (needs tb/seq_acc/inputs/* generated by pytest)
  tb_qracc_top     CLEAN ERROR            (needs tb/qracc_top/inputs/* + commands.txt)
  tb_q_redis       PROPRIETARY            (xrun/Cadence only; not verilator)

Examples:
  $0 tb_column
  $0 tb_qracc        # fails with [TB ERROR] cannot open input file if inputs are missing
EOF
    exit 0
}

if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]; then
    usage
fi

TB="${1:-}"
if [[ -z "$TB" ]]; then
    echo "Error: no testbench name given. Run '$0 --help' for usage." >&2
    exit 2
fi

# Map tb name -> (tb source path, top module, extra rtl sources beyond the package)
case "$TB" in
    tb_column)
        TB_SRC="../tb/tb_column.sv"
        TOP_MODULE="tb_column"
        RTL_SRCS=(
            "../rtl/qracc_pkg.svh"
            "../rtl/column_wrapper.sv"
            "../rtl/wr_controller.sv"
            "../rtl/ts_column.sv"
        )
        ;;
    tb_afl)
        TB_SRC="../tb/afl/tb_afl.sv"
        TOP_MODULE="tb_afl"
        RTL_SRCS=(
            "../rtl/qracc_pkg.svh"
        )
        ;;
    tb_qracc)
        TB_SRC="../tb/qracc/tb_qracc.sv"
        TOP_MODULE="tb_qracc"
        RTL_SRCS=(
            "../rtl/qracc_params_defaults.svh"
            "../rtl/qracc_pkg.svh"
            "../rtl/qr_acc_wrapper.sv"
            "../rtl/ts_qracc.sv"
            "../rtl/wr_controller.sv"
            "../rtl/twos_to_bipolar.sv"
        )
        ;;
    tb_seq_acc)
        TB_SRC="../tb/seq_acc/tb_seq_acc.sv"
        TOP_MODULE="tb_seq_acc"
        RTL_SRCS=(
            "../rtl/qracc_params_defaults.svh"
            "../rtl/qracc_pkg.svh"
            "../rtl/qr_acc_wrapper.sv"
            "../rtl/seq_acc.sv"
            "../rtl/ts_qracc.sv"
            "../rtl/wr_controller.sv"
            "../rtl/twos_to_bipolar.sv"
        )
        ;;
    tb_qracc_top)
        TB_SRC="../tb/qracc_top/tb_qracc_top.sv"
        TOP_MODULE="tb_qracc_top"
        RTL_SRCS=(
            "../rtl/qracc_params_defaults.svh"
            "../rtl/qracc_pkg.svh"
            "../rtl/qr_acc_top.sv"
            "../rtl/qr_acc_wrapper.sv"
            "../rtl/activation_buffer/piso_write_queue.sv"
            "../rtl/activation_buffer/mm_output_aligner.sv"
            "../rtl/wsacc/wsacc_pe_cluster.sv"
            "../rtl/wsacc/wsacc_pe.sv"
            "../rtl/seq_acc.sv"
            "../rtl/ts_qracc.sv"
            "../rtl/wr_controller.sv"
            "../rtl/twos_to_bipolar.sv"
            "../rtl/output_scaler/output_scaler_set.sv"
            "../rtl/output_scaler/output_scaler.sv"
            "../rtl/memory/ram_2w2r.sv"
            "../rtl/feature_loader/feature_loader.sv"
            "../rtl/feature_loader/padder.sv"
            "../rtl/control/qracc_csr.sv"
            "../rtl/control/qracc_controller.sv"
        )
        ;;
    tb_q_redis)
        echo "Error: tb_q_redis is PROPRIETARY (xrun/Cadence only); not supported by this verilator script." >&2
        exit 2
        ;;
    *)
        echo "Error: unknown testbench '$TB'. Run '$0 --help' for the list." >&2
        exit 2
        ;;
esac

echo "=====VERILATOR COMPILE ($TB)====="
verilator "${VERILATOR_ARGS[@]}" \
    "${RTL_SRCS[@]}" \
    "$TB_SRC" \
    --top-module "$TOP_MODULE" \
    -o "V${TOP_MODULE}" \
    --Mdir "obj_dir_${TOP_MODULE}"

echo "=====VERILATOR RUN ($TB)====="
"./obj_dir_${TOP_MODULE}/V${TOP_MODULE}"
